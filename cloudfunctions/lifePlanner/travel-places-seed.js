const TRAVEL_PLACES = [...BEIJING_PLACES, ...OUTSIDE_PLACES]

function validateTravelSeed() {
  const byType = { beijing: 0, outside: 0 }
  const seen = new Set()
  const problems = []
  for (const p of TRAVEL_PLACES) {
    byType[p.type] = (byType[p.type] || 0) + 1
    const key = p.name + '/' + p.type
    if (seen.has(key)) problems.push('重复: ' + key)
    seen.add(key)
    if (!p.shortIntro) problems.push('缺简介: ' + p.name)
    if (!Array.isArray(p.highlights) || !p.highlights.length) problems.push('缺亮点: ' + p.name)
    if (!p.plan || !Array.isArray(p.plan.days) || !p.plan.days.length) problems.push('缺计划: ' + p.name)
    if (p.type === 'beijing' && p.defaultDays !== 1) problems.push('北京天数错: ' + p.name)
    if (p.type === 'outside' && p.defaultDays !== 3) problems.push('外地天数错: ' + p.name)
  }
  return { total: TRAVEL_PLACES.length, byType, problems }
}

module.exports = { TRAVEL_PLACES, TRAVEL_SEED_VERSION, validateTravelSeed }
