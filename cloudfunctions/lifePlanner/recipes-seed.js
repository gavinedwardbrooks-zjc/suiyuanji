function validateSeed() {
  const byCat = { meat: 0, vegetable: 0, soup: 0 }
  const seen = new Set()
  const problems = []
  for (const r of SEED_RECIPES) {
    byCat[r.category] = (byCat[r.category] || 0) + 1
    const key = r.name + '/' + r.category
    if (seen.has(key)) problems.push('重复: ' + key)
    seen.add(key)
    if (!Array.isArray(r.ingredients) || !r.ingredients.length) problems.push('缺食材: ' + r.name)
    if (!Array.isArray(r.steps) || !r.steps.length) problems.push('缺步骤: ' + r.name)
    if (!Array.isArray(r.tips) || !r.tips.length) problems.push('缺贴士: ' + r.name)
  }
  return { total: SEED_RECIPES.length, byCat, problems }
}

module.exports = { SEED_RECIPES, SEED_VERSION, validateSeed }
